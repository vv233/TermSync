const QVector<ColorScheme> &builtinSchemes()
{
    return schemes();
}

const ColorScheme *findScheme(const QString &name)
{
    for (const ColorScheme &s : schemes())
        if (s.name == name)
            return &s;
    return nullptr;
}

QString defaultSchemeName()
{
    return schemes().front().name;
}

