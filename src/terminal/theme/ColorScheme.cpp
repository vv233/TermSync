// Helper to keep the table below compact and readable.
ColorScheme make(const char *name, bool dark, uint32_t bg, uint32_t fg,
                 uint32_t cursor, const uint32_t (&ansi)[16])
{
    ColorScheme s;
    s.name = QString::fromLatin1(name);
    s.dark = dark;
    s.background = bg;
    s.foreground = fg;
    s.cursor = cursor;
    for (int i = 0; i < 16; ++i)
        s.ansi[i] = ansi[i];
    return s;
}

